#!/usr/bin/env node

/**
 * Demo Chat Selector
 * Selects a conversation from interlocutor-conversations.json by title
 * and extracts its messages to create a demo chat file
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

/**
 * Demo Chat Selector Class
 */
class DemoChatSelector {
  constructor() {
    this.conversations = [];
  }

  /**
   * Load conversations from file
   */
  loadConversations(filePath) {
    // Resolve relative to script directory if relative path
    let resolvedPath = filePath;
    if (!path.isAbsolute(filePath)) {
      resolvedPath = path.resolve(__dirname, filePath);
    }

    if (!fs.existsSync(resolvedPath)) {
      throw new Error(`File not found: ${resolvedPath}`);
    }

    const content = fs.readFileSync(resolvedPath, 'utf8');
    this.conversations = JSON.parse(content);

    if (!Array.isArray(this.conversations)) {
      throw new Error('Conversations file must contain an array');
    }

    console.log(
      `Loaded ${this.conversations.length} conversations from ${resolvedPath}`
    );
  }

  /**
   * List all conversations with their titles
   */
  listConversations() {
    if (this.conversations.length === 0) {
      console.log('No conversations loaded');
      return;
    }

    console.log('\nAvailable conversations:');
    console.log('='.repeat(50));

    this.conversations.forEach((conv, index) => {
      const messageCount = conv.messages ? conv.messages.length : 0;
      console.log(`${index + 1}. "${conv.title}" (${messageCount} messages)`);
    });

    console.log('='.repeat(50));
  }

  /**
   * Find conversation by title (partial match)
   */
  findByTitle(searchTitle) {
    const matches = this.conversations.filter((conv) =>
      conv.title.toLowerCase().includes(searchTitle.toLowerCase())
    );

    if (matches.length === 0) {
      return null;
    } else if (matches.length === 1) {
      return matches[0];
    } else {
      console.log(`\nMultiple matches found for "${searchTitle}":`);
      matches.forEach((conv, index) => {
        console.log(`${index + 1}. "${conv.title}"`);
      });
      return matches[0]; // Return first match
    }
  }

  /**
   * Get conversation by index (1-based)
   */
  getByIndex(index) {
    const actualIndex = index - 1;
    if (actualIndex < 0 || actualIndex >= this.conversations.length) {
      throw new Error(
        `Invalid index: ${index}. Must be between 1 and ${this.conversations.length}`
      );
    }
    return this.conversations[actualIndex];
  }

  /**
   * Extract messages from a conversation and format for demo use
   */
  extractMessages(conversation) {
    if (!conversation.messages || !Array.isArray(conversation.messages)) {
      throw new Error('Conversation does not contain valid messages');
    }

    return conversation.messages;
  }

  /**
   * Save messages to demo chat file
   */
  saveDemoChat(messages, outputPath) {
    // Resolve relative to script directory if relative path
    let resolvedPath = outputPath;
    if (!path.isAbsolute(outputPath)) {
      resolvedPath = path.resolve(__dirname, outputPath);
    }

    // Format as JavaScript array for easy import
    const jsContent = `// Demo chat messages for "${messages.length > 0 ? 'Selected Conversation' : 'Empty'}"
// Generated by select-demo-chat.js

export const demoMessages = ${JSON.stringify(messages, null, 2)};
`;

    fs.writeFileSync(resolvedPath, jsContent);
    console.log(`Demo chat saved to ${resolvedPath}`);
    console.log(`Contains ${messages.length} messages`);
  }

  /**
   * Interactive selection mode
   */
  async selectInteractively() {
    const readline = await import('readline');
    const rl = readline.createInterface({
      input: process.stdin,
      output: process.stdout,
    });

    return new Promise((resolve) => {
      rl.question('\nEnter conversation number or title: ', (answer) => {
        rl.close();

        // Try as number first
        const num = parseInt(answer.trim());
        if (!isNaN(num)) {
          try {
            const conversation = this.getByIndex(num);
            resolve(conversation);
            return;
          } catch (error) {
            console.log(`Invalid number: ${error.message}`);
          }
        }

        // Try as title search
        const conversation = this.findByTitle(answer.trim());
        if (conversation) {
          resolve(conversation);
        } else {
          console.log(`No conversation found matching "${answer}"`);
          resolve(null);
        }
      });
    });
  }
}

// CLI functionality
async function main() {
  const args = process.argv.slice(2);

  if (args.length === 0) {
    console.log('Usage:');
    console.log(
      '  node select-demo-chat.js <conversations-file> [output-file] [--interactive]'
    );
    console.log('  node select-demo-chat.js <conversations-file> --list');
    console.log('  node select-demo-chat.js --help');
    console.log('');
    console.log('Examples:');
    console.log('  node select-demo-chat.js interlocutor-conversations.json');
    console.log(
      '  node select-demo-chat.js conversations.json demo-chat.js --interactive'
    );
    console.log('  node select-demo-chat.js conversations.json --list');
    console.log(
      '  node select-demo-chat.js conversations.json --title "XGBoost" demo-chat.js'
    );
    return;
  }

  if (args[0] === '--help' || args[0] === '-h') {
    await main(); // Show usage
    return;
  }

  const selector = new DemoChatSelector();

  try {
    let inputFile = null;
    let outputFile = 'demo-chat.js';
    let interactive = false;
    let listOnly = false;
    let titleSearch = null;

    // Parse arguments
    for (let i = 0; i < args.length; i++) {
      if (args[i] === '--interactive' || args[i] === '-i') {
        interactive = true;
      } else if (args[i] === '--list' || args[i] === '-l') {
        listOnly = true;
      } else if (args[i] === '--title' || args[i] === '-t') {
        titleSearch = args[i + 1];
        i++; // Skip next arg
      } else if (!args[i].startsWith('-') && !inputFile) {
        inputFile = args[i];
      } else if (!args[i].startsWith('-')) {
        outputFile = args[i];
      }
    }

    if (!inputFile && !listOnly) {
      console.log('Error: Input file is required (unless using --list)');
      console.log('Run with --help for usage information');
      return;
    }

    // Load conversations (required for all modes except help)
    if (inputFile) {
      console.log(`Loading conversations from ${inputFile}...`);
      selector.loadConversations(inputFile);
    } else if (listOnly) {
      console.log('Error: --list requires an input file');
      console.log(
        'Usage: node select-demo-chat.js <conversations-file> --list'
      );
      return;
    }

    // List only mode
    if (listOnly) {
      selector.listConversations();
      return;
    }

    let selectedConversation = null;

    // Title search mode
    if (titleSearch) {
      console.log(
        `Searching for conversation with title containing "${titleSearch}"...`
      );
      selectedConversation = selector.findByTitle(titleSearch);
      if (!selectedConversation) {
        console.log(
          `No conversation found with title containing "${titleSearch}"`
        );
        return;
      }
    }
    // Interactive mode
    else if (interactive) {
      selector.listConversations();
      selectedConversation = await selector.selectInteractively();
      if (!selectedConversation) {
        console.log('No conversation selected');
        return;
      }
    }
    // Default: use first conversation
    else {
      if (selector.conversations.length === 0) {
        console.log('No conversations available');
        return;
      }
      selectedConversation = selector.conversations[0];
      console.log(`Using first conversation: "${selectedConversation.title}"`);
    }

    // Extract and save
    console.log(`\nSelected: "${selectedConversation.title}"`);
    const messages = selector.extractMessages(selectedConversation);
    selector.saveDemoChat(messages, outputFile);
  } catch (error) {
    console.error('Error:', error.message);
    process.exit(1);
  }
}

// Run CLI if called directly
if (process.argv[1] && process.argv[1].includes('select-demo-chat.js')) {
  main().catch((error) => {
    console.error('Error:', error.message);
    process.exit(1);
  });
}
